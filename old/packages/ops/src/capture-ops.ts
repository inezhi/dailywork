export const captureOps = [
  defineOp({
    name: 'memo.list',
    version: 1,
    kind: 'query',
    summary: '列出速记卡片',
    input: ListMemosInput,
    exposure: { http: true, cli: ['memo', 'list'], mcp: true, ai: true },
    aggregate: 'memo',
    handler: (ctx, input) => listMemos(ctx.db, input),
  }),
  defineOp({
    name: 'memo.create',
    version: 1,
    kind: 'command',
    summary: '创建速记卡片（支持 #标签）',
    input: CreateMemoInput,
    exposure: { http: true, cli: ['memo', 'create'], mcp: true, ai: true },
    annotations: { idempotent: false },
    aggregate: 'memo',
    handler: (ctx, input) => createMemo(ctx.db, input),
  }),
  defineOp({
    name: 'memo.get',
    version: 1,
    kind: 'query',
    summary: '读取速记',
    input: MemoRefInput,
    exposure: { http: true, cli: ['memo', 'get'], mcp: true, ai: true },
    aggregate: 'memo',
    handler: (ctx, input) => getMemo(ctx.db, input.id),
  }),
  defineOp({
    name: 'memo.update',
    version: 1,
    kind: 'command',
    summary: '更新速记',
    input: UpdateMemoInput,
    exposure: { http: true, cli: ['memo', 'update'], mcp: true, ai: true },
    annotations: { idempotent: true },
    aggregate: 'memo',
    handler: (ctx, input) => updateMemo(ctx.db, input),
  }),
  defineOp({
    name: 'memo.delete',
    version: 1,
    kind: 'command',
    summary: '删除速记',
    input: MemoRefInput,
    exposure: { http: true, cli: ['memo', 'delete'], mcp: true, ai: true },
    annotations: { destructive: true, confirm: true },
    aggregate: 'memo',
    handler: (ctx, input) => deleteMemo(ctx.db, input.id),
  }),
  defineOp({
    name: 'memo.stats',
    version: 1,
    kind: 'query',
    summary: '速记统计与标签云',
    input: z.object({}),
    exposure: { http: true, cli: ['memo', 'stats'], mcp: true, ai: true },
    aggregate: 'memo',
    handler: (ctx) => memoStats(ctx.db),
  }),
  defineOp({
    name: 'memo.toTask',
    version: 1,
    kind: 'command',
    summary: '把速记转为任务',
    input: MemoToTaskInput,
    exposure: { http: true, cli: ['memo', 'to-task'], mcp: true, ai: true },
    annotations: { idempotent: false },
    aggregate: 'memo',
    handler: (ctx, input) => memoToTask(ctx.db, input),
  }),
  defineOp({
    name: 'inbox.capture',
    version: 1,
    kind: 'command',
    summary: '快速捕获到收件箱（速记或任务）',
    input: InboxCaptureInput,
    exposure: { http: true, cli: ['inbox', 'capture'], mcp: true, ai: true },
    annotations: { idempotent: false },
    aggregate: 'memo',
    handler: (ctx, input) => captureInbox(ctx.db, input),
  }),
  defineOp({
    name: 'inbox.list',
    version: 1,
    kind: 'query',
    summary: '收件箱列表（未整理任务与速记）',
    input: z.object({ limit: z.number().int().min(1).max(200).default(50) }),
    exposure: { http: true, cli: ['inbox', 'list'], mcp: true, ai: true },
    aggregate: 'memo',
    handler: (ctx, input): InboxItem[] => {
      const tasks = listTasks(ctx, {
        status: ['inbox'],
        limit: input.limit,
        offset: 0,
        sort: 'created',
      }).items
      const memos = listMemos(ctx.db, { limit: input.limit, offset: 0 }).items.filter(
        (m) => !m.convertedTaskId,
      )
      const items: InboxItem[] = [
        ...tasks.map((t) => ({
          id: `task:${t.id}`,
          ownerType: 'task' as const,
          ownerId: t.id,
          preview: t.title,
          createdAt: t.createdAt,
        })),
        ...memos.map((m) => ({
          id: `memo:${m.id}`,
          ownerType: 'memo' as const,
          ownerId: m.id,
          preview: m.content.slice(0, 160),
          createdAt: m.createdAt,
        })),
      ]
      return items.sort((a, b) => b.createdAt.localeCompare(a.createdAt)).slice(0, input.limit)
    },
  }),
]

