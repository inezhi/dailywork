import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } })
const page = await context.newPage()
await page.goto('http://127.0.0.1:5173/today', { waitUntil: 'networkidle' })
await page.locator('.auth-shell').waitFor()
await page.getByRole('tab', { name: '注册' }).click()
await page.waitForTimeout(300)
const authText = await page.locator('.auth-shell').innerText()
console.log('auth copy chars', authText.length)
await page.screenshot({ path: 'design/qa/auth-register.png' })
await page.getByRole('tab', { name: '登录' }).click()
await page.getByPlaceholder('你的用户名').fill('验收用户')
await page.getByPlaceholder('至少 8 位').fill('verify-pass-123')
await page.locator('.auth-submit').click()
await page.locator('.app').waitFor({ timeout: 15000 })
await page.waitForTimeout(600)
await page.screenshot({ path: 'design/qa/blue-today.png' })
const avatar = await page.locator('.topbar .avatar').innerText()
console.log('avatar', avatar)
await page.goto('http://127.0.0.1:5173/settings', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: '账户' }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: 'design/qa/account-settings.png' })
await browser.close()
