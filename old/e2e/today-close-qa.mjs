import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto('http://127.0.0.1:5173/focus', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /开始 25 分钟专注/ }).click()
await page.locator('.focus-stage').waitFor()
await page.waitForTimeout(1200)
await page.screenshot({ path: 'design/qa/focus-active.png' })
await page.getByRole('button', { name: /放弃本次/ }).click()
await page.waitForTimeout(800)
await page.goto('http://127.0.0.1:5173/today', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /收尾/ }).click()
await page.locator('.modal').waitFor()
await page.waitForTimeout(400)
await page.screenshot({ path: 'design/qa/today-close.png' })
console.log('errors', errors)
await browser.close()
