import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto('http://127.0.0.1:5173/today', { waitUntil: 'networkidle' })
await page.locator('button[aria-label="AI 助理"]').click()
await page.locator('.ai-panel textarea').fill('今天怎么样？')
await page.locator('.ai-send').click()
await page.waitForTimeout(700)
const partial = await page.locator('.ai-msg.assistant .ai-bubble').last().innerText().catch(() => '')
console.log('partial', JSON.stringify(partial.slice(0, 80)))
await page.screenshot({ path: 'design/qa/ai-streaming.png' })
await page.waitForTimeout(1600)
const final = await page.locator('.ai-msg.assistant .ai-bubble').last().innerText().catch(() => '')
console.log('final', JSON.stringify(final.slice(0, 120)))
const tools = await page.locator('.ai-tool').allInnerTexts().catch(() => [])
console.log('tools', tools)
console.log('errors', errors)
await browser.close()
