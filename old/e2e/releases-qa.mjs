import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
await page.goto('http://127.0.0.1:5173/today', { waitUntil: 'networkidle' })
await page.getByPlaceholder('你的用户名').fill('验收用户')
await page.getByPlaceholder('至少 8 位').fill('verify-pass-123')
await page.locator('.auth-submit').click()
await page.locator('.app').waitFor({ timeout: 15000 })
await page.goto('http://127.0.0.1:5173/settings', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: '关于' }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: 'design/qa/about-version.png', fullPage: true })
await page.getByRole('button', { name: '查看全部版本' }).click()
await page.locator('.modal').waitFor()
await page.waitForTimeout(300)
await page.screenshot({ path: 'design/qa/release-notes.png' })
const text = await page.locator('.modal').innerText()
console.log('versions', text.includes('v0.2.0'), text.includes('v0.1.0'), 'length', text.length)
await browser.close()
