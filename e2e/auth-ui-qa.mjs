import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:5173/today', { waitUntil: 'networkidle' })
await page.locator('.auth-shell').waitFor({ timeout: 10000 })
await page.screenshot({ path: 'design/qa/auth-register.png' })
console.log('heading', await page.locator('.auth-heading h2').innerText())
await page.locator('input[autocomplete="username"]').fill('验收用户')
await page.getByPlaceholder('至少 8 位').fill('verify-pass-123')
await page.getByPlaceholder('再输入一次').fill('verify-pass-123')
await page.locator('.auth-submit').click()
await page.locator('.app').waitFor({ timeout: 15000 })
await page.waitForTimeout(800)
const avatarText = await page.locator('.topbar .avatar').innerText()
console.log('avatar initial', avatarText)
await page.screenshot({ path: 'design/qa/auth-logged-in.png' })
await page.goto('http://127.0.0.1:5173/settings', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: '账户' }).click()
await page.waitForTimeout(500)
await page.screenshot({ path: 'design/qa/account-settings.png' })
console.log('errors', errors)
await browser.close()
