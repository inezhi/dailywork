import { z } from 'zod'
import {
  CreateTagInput,
  CreateTaskInput,
  Id,
  ListTasksInput,
  MoveTaskInput,
  TagRefInput,
  TaskRefInput,
  UpdateTagInput,
  UpdateTaskInput,
} from '@daily/contracts'
import {
  completeTask,
  createTag,
  createTask,
  deleteTag,
  deleteTask,
  getTask,
  listTags,
  listTasks,
  moveTask,
  reopenTask,
  taskActivity,
  updateTag,
  updateTask,
} from '@daily/context-tasking'
import { defineOp } from './core.js'

function taskCtx(ctx: Parameters<typeof createTask>[0]) {
  return ctx
}

export const taskOps = [
  defineOp({
    name: 'task.create',
    version: 1,
    kind: 'command',
    summary: '创建一个任务',
    description: '创建任务；支持父任务、项目、计划日期、截止日期、预估与标签。传入 opId 可安全重试。',
    input: CreateTaskInput,
    exposure: { http: true, cli: ['task', 'create'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['VALIDATION_ERROR', 'NOT_FOUND', 'BAD_REQUEST'],
    aggregate: 'task',
    handler: (ctx, input) => createTask(taskCtx(ctx), input),
  }),
  defineOp({
    name: 'task.update',
    version: 1,
    kind: 'command',
    summary: '更新任务字段',
    input: UpdateTaskInput,
    exposure: { http: true, cli: ['task', 'update'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['NOT_FOUND', 'VERSION_CONFLICT', 'BAD_REQUEST'],
    aggregate: 'task',
    handler: (ctx, input) => updateTask(ctx, input),
  }),
  defineOp({
    name: 'task.move',
    version: 1,
    kind: 'command',
    summary: '移动任务到另一个状态或位置',
    input: MoveTaskInput,
    exposure: { http: true, cli: ['task', 'move'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['NOT_FOUND', 'VERSION_CONFLICT'],
    aggregate: 'task',
    handler: (ctx, input) => moveTask(ctx, input),
  }),
  defineOp({
    name: 'task.complete',
    version: 1,
    kind: 'command',
    summary: '把任务标记为完成',
    input: TaskRefInput,
    exposure: { http: true, cli: ['task', 'complete'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['NOT_FOUND', 'VERSION_CONFLICT'],
    aggregate: 'task',
    handler: (ctx, input) => completeTask(ctx, input),
  }),
  defineOp({
    name: 'task.reopen',
    version: 1,
    kind: 'command',
    summary: '重新打开已完成任务',
    input: TaskRefInput,
    exposure: { http: true, cli: ['task', 'reopen'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['NOT_FOUND'],
    aggregate: 'task',
    handler: (ctx, input) => reopenTask(ctx, input),
  }),
  defineOp({
    name: 'task.delete',
    version: 1,
    kind: 'command',
    summary: '删除任务及其子任务',
    input: TaskRefInput,
    exposure: { http: true, cli: ['task', 'delete'], mcp: true, ai: true },
    annotations: { destructive: true, confirm: true },
    errors: ['NOT_FOUND'],
    aggregate: 'task',
    handler: (ctx, input) => deleteTask(ctx, input),
  }),
  defineOp({
    name: 'task.get',
    version: 1,
    kind: 'query',
    summary: '按 ID 读取任务',
    input: z.object({ id: Id }),
    exposure: { http: true, cli: ['task', 'get'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => getTask(ctx.db, input.id),
  }),
  defineOp({
    name: 'task.list',
    version: 1,
    kind: 'query',
    summary: '查询任务列表',
    description: '按状态、空间、项目、标签、日期、关键字筛选任务，默认排除子任务与归档。',
    input: ListTasksInput,
    exposure: { http: true, cli: ['task', 'list'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => listTasks(ctx, input),
  }),
  defineOp({
    name: 'task.activity',
    version: 1,
    kind: 'query',
    summary: '读取任务的操作记录',
    input: z.object({ id: Id, limit: z.number().int().min(1).max(200).default(40) }),
    exposure: { http: true, cli: ['task', 'activity'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => taskActivity(ctx.db, input.id, input.limit),
  }),

  defineOp({
    name: 'tag.list',
    version: 1,
    kind: 'query',
    summary: '列出标签及任务数量',
    input: z.object({}),
    exposure: { http: true, cli: ['tag', 'list'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx) => listTags(ctx.db),
  }),
  defineOp({
    name: 'tag.create',
    version: 1,
    kind: 'command',
    summary: '创建标签（同名复用）',
    input: CreateTagInput,
    exposure: { http: true, cli: ['tag', 'create'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['CONFLICT'],
    aggregate: 'task',
    handler: (ctx, input) => createTag(ctx.db, input),
  }),
  defineOp({
    name: 'tag.update',
    version: 1,
    kind: 'command',
    summary: '重命名或改色标签',
    input: UpdateTagInput,
    exposure: { http: true, cli: ['tag', 'update'], mcp: true, ai: true },
    annotations: { idempotent: true },
    errors: ['NOT_FOUND', 'CONFLICT'],
    aggregate: 'task',
    handler: (ctx, input) => updateTag(ctx.db, input),
  }),
  defineOp({
    name: 'tag.delete',
    version: 1,
    kind: 'command',
    summary: '删除标签',
    input: TagRefInput,
    exposure: { http: true, cli: ['tag', 'delete'], mcp: true, ai: true },
    annotations: { destructive: true, confirm: true },
    aggregate: 'task',
    handler: (ctx, input) => deleteTag(ctx.db, input.id),
  }),
]
