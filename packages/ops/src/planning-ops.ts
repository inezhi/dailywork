import { z } from 'zod'
import {
  CalendarRangeInput,
  CreateRoutineInput,
  DayInput,
  FinishFocusInput,
  FocusRefInput,
  ListFocusInput,
  RoutineRefInput,
  SetCapacityInput,
  StartFocusInput,
  TimelineRangeInput,
  WeekReviewInput,
  Id,
  type TodayResult,
} from '@daily/contracts'
import {
  calendarRange,
  createRoutine,
  dayPlan,
  deleteRoutine,
  listRoutines,
  setCapacity,
  timelineRange,
  todaySummary,
  toggleRoutine,
  weekReview,
} from '@daily/context-planning'
import {
  countInbox,
  tasksCompletedBetween,
  tasksDueOn,
  tasksOverdue,
} from '@daily/context-tasking'
import {
  activeSession,
  cancelFocus,
  finishFocus,
  focusDayBuckets,
  focusStats,
  listFocus,
  startFocus,
} from '@daily/context-focus'
import { localDayBoundsUtc, todayLocal } from '@daily/platform'
import { defineOp } from './core.js'

export const planningOps = [
  defineOp({
    name: 'today.get',
    version: 1,
    kind: 'query',
    summary: '今天的计划、容量、逾期与专注汇总',
    input: DayInput.partial({ date: true }),
    exposure: { http: true, cli: ['today'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input): TodayResult => {
      const date = input.date ?? todayLocal()
      const plan = todaySummary(ctx.db, date, input.spaceId)
      const bounds = localDayBoundsUtc(date)
      return {
        date,
        capacityMinutes: plan.capacityMinutes,
        note: plan.note,
        scheduled: plan.tasks,
        due: tasksDueOn(ctx.db, date, input.spaceId),
        overdue: tasksOverdue(ctx.db, date, input.spaceId),
        completed: tasksCompletedBetween(ctx.db, bounds.start, bounds.end, input.spaceId),
        inboxCount: countInbox(ctx.db, input.spaceId),
        focusMinutes: plan.focusMinutes,
        plannedMinutes: plan.plannedMinutes,
        completedMinutes: plan.completedMinutes,
      }
    },
  }),
  defineOp({
    name: 'day.get',
    version: 1,
    kind: 'query',
    summary: '某一天的计划与容量',
    input: DayInput,
    exposure: { http: true, cli: ['day', 'get'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => {
      const plan = dayPlan(ctx.db, input.date, input.spaceId)
      return {
        date: plan.date,
        capacityMinutes: plan.capacityMinutes,
        note: plan.note,
        plannedMinutes: plan.plannedMinutes,
        completedMinutes: plan.completedMinutes,
        tasks: plan.tasks,
      }
    },
  }),
  defineOp({
    name: 'capacity.set',
    version: 1,
    kind: 'command',
    summary: '设置某天的可用时长',
    input: SetCapacityInput,
    exposure: { http: true, cli: ['capacity', 'set'], mcp: true, ai: true },
    annotations: { idempotent: true },
    aggregate: 'task',
    handler: (ctx, input) => setCapacity(ctx.db, input),
  }),
  defineOp({
    name: 'calendar.range',
    version: 1,
    kind: 'query',
    summary: '查询日期区间内的日历事件',
    input: CalendarRangeInput,
    exposure: { http: true, cli: ['calendar', 'range'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => calendarRange(ctx.db, input),
  }),
  defineOp({
    name: 'timeline.range',
    version: 1,
    kind: 'query',
    summary: '查询时间轴（甘特）条目',
    input: TimelineRangeInput,
    exposure: { http: true, cli: ['timeline', 'range'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => timelineRange(ctx.db, input),
  }),
  defineOp({
    name: 'review.week',
    version: 1,
    kind: 'query',
    summary: '生成本周复盘数据',
    input: WeekReviewInput,
    exposure: { http: true, cli: ['review', 'week'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx, input) => weekReview(ctx.db, input.weekStart),
  }),
  defineOp({
    name: 'routine.list',
    version: 1,
    kind: 'query',
    summary: '列出每日例程',
    input: z.object({}),
    exposure: { http: true, cli: ['routine', 'list'], mcp: true, ai: true },
    aggregate: 'task',
    handler: (ctx) => listRoutines(ctx.db),
  }),
  defineOp({
    name: 'routine.create',
    version: 1,
    kind: 'command',
    summary: '创建每日例程',
    input: CreateRoutineInput,
    exposure: { http: true, cli: ['routine', 'create'], mcp: true, ai: true },
    annotations: { idempotent: false },
    aggregate: 'task',
    handler: (ctx, input) => createRoutine(ctx.db, input),
  }),
  defineOp({
    name: 'routine.toggle',
    version: 1,
    kind: 'command',
    summary: '启用或停用例程',
    input: z.object({ id: Id, enabled: z.boolean() }),
    exposure: { http: true, cli: ['routine', 'toggle'], mcp: true, ai: true },
    annotations: { idempotent: true },
    aggregate: 'task',
    handler: (ctx, input) => toggleRoutine(ctx.db, input.id, input.enabled),
  }),
  defineOp({
    name: 'routine.delete',
    version: 1,
    kind: 'command',
    summary: '删除例程',
    input: RoutineRefInput,
    exposure: { http: true, cli: ['routine', 'delete'], mcp: true, ai: true },
    annotations: { destructive: true, confirm: true },
    aggregate: 'task',
    handler: (ctx, input) => deleteRoutine(ctx.db, input.id),
  }),
]

